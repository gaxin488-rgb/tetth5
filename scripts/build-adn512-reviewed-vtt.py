def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    return parser.parse_args()


def build_vtt(input_path: Path, output_path: Path) -> int:
    blocks = re.split(r"\n\s*\n", input_path.read_text(encoding="utf-8-sig").strip())
    rendered: list[str] = []
    cue_count = 0
    for block in blocks:
        lines = block.splitlines()
        time_index = next((i for i, line in enumerate(lines) if TIME_RE.match(line)), None)
        if time_index is None:
            if block.strip().upper() != "WEBVTT":
                rendered.append(block)
            continue
        number = int(lines[time_index - 1]) if time_index > 0 and lines[time_index - 1].isdigit() else cue_count + 1
        cue_count += 1
        text = TRANSLATIONS.get(number, "[…]")
        rendered.append("\n".join(lines[: time_index + 1] + [text]))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "WEBVTT\n\n"
        "NOTE CineZero reviewed Vietnamese subtitle\n"
        "NOTE source-language=ja\n"
        "NOTE target-language=vi\n"
        "NOTE translation=cue-by-cue-context-review\n\n"
        + "\n\n".join(rendered)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return cue_count


if __name__ == "__main__":
    args = parse_args()
    count = build_vtt(args.input, args.output)
    print(f"REVIEWED_CUES={count}")
    print(f"VTT_OUTPUT={args.output}")
